// resources 按语言查资源。System 与陌生取值都退到英文。
var resources = map[string]messages{
	EN: enMessages,
	ZH: zhMessages,
}

// T 返回 key 在 lang 下的文案。args 是成对的占位符名与取值，替换文案里的 {name}。缺翻译时用英文；
// 两种语言都没有这个键时返回键名本身，测试里一眼能看出来。
func T(lang, key string, args ...string) string {
	text := resources[lang][key]
	if text == "" {
		text = enMessages[key]
	}
	if text == "" {
		return key
	}
	if len(args) == 0 {
		return text
	}
	for i := 0; i+1 < len(args); i += 2 {
		text = strings.ReplaceAll(text, "{"+args[i]+"}", args[i+1])
	}
	return text
}

// Resolve 决定界面语言：显式选择优先；跟随系统时按系统语言列表匹配，匹配不上就用英文（源语言）。
func Resolve(pref string, preferred []string) string {
	if pref == EN || pref == ZH {
		return pref
	}
	if match := mygoi18n.Match(preferred, uiLanguages); match != "" {
		return match
	}
	return EN
}

// Label 是语言选择里显示的名字：语言自己的写法（English、简体中文）。
func Label(tag string) string {
	if tag == System {
		return ""
	}
	if name := mygoi18n.Autonym(tag); name != "" {
		return name
	}
	return tag
}

// Valid 报告 pref 是不是可选的语言偏好（跟随系统、英文或简体中文）。
func Valid(pref string) bool {
	switch pref {
	case System, EN, ZH:
		return true
	}
	return false
}

// Has 报告 lang 的资源里有没有 key（核对代码用到的文案是否齐全）。
func Has(lang, key string) bool {
	_, ok := resources[lang][key]
	return ok
}

// Keys 返回源语言（英文）资源里的全部键。
func Keys() []string {
	keys := make([]string, 0, len(enMessages))
	for key := range enMessages {
		keys = append(keys, key)
	}
	return keys
}
